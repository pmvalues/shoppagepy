"""One-off converter: packages/kernel TS taxonomy -> apps/catalog/taxonomy_data.py"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / 'packages' / 'kernel' / 'src' / 'taxonomy' / 'google_taxonomy.ts'
OUT = ROOT / 'apps' / 'catalog' / 'taxonomy_data.py'

text = SRC.read_text(encoding='utf-8')
pattern = re.compile(
    r"\{\s*id:\s*(\d+),\s*name:\s*'([^']*)',\s*fullPath:\s*'([^']*)',"
    r"(?:\s*parentId:\s*(\d+),)?\s*level:\s*(\d+),\s*slug:\s*'([^']*)'\s*\}"
)
rows = []
seen = set()
for m in pattern.finditer(text):
    cid, name, full_path, parent, level, slug = m.groups()
    if cid in seen:
        continue
    seen.add(cid)
    rows.append((int(cid), name, full_path, int(parent) if parent else None, int(level), slug))

rows.sort(key=lambda r: (r[4], r[2].lower()))
if len(rows) < 5000:
    print(f'ERROR: only parsed {len(rows)} rows, expected ~5595', file=sys.stderr)
    sys.exit(1)

with OUT.open('w', encoding='utf-8', newline='\n') as f:
    f.write('"""Google Product Taxonomy (en-US, 2021-09-21) + Shoppage SA extensions.\n\n')
    f.write('Generated by scripts/convert_taxonomy.py from packages/kernel/src/taxonomy/google_taxonomy.ts.\n')
    f.write('Do not edit by hand; re-run the converter instead.\n"""\n\n')
    f.write('# (id, name, full_path, parent_id, level, slug)\n')
    f.write('GOOGLE_TAXONOMY = [\n')
    for cid, name, full_path, parent, level, slug in rows:
        f.write(f'    ({cid}, {name!r}, {full_path!r}, {parent!r}, {level}, {slug!r}),\n')
    f.write(']\n')

print(f'OK: wrote {len(rows)} categories to {OUT}')
